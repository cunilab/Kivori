// Build the public catalog subset from the same registry used by desktop and firmware.
import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import prettier from 'prettier';

const webRoot = fileURLToPath(new URL('..', import.meta.url));
const repoRoot = fileURLToPath(new URL('../../..', import.meta.url));
const toml = async (path) => Bun.TOML.parse(await readFile(path, 'utf8'));
const registry = await toml(join(repoRoot, 'products/registry.toml'));
const products = [];
const numbers = new Set();
const models = new Set();
for (const [id, wire] of Object.entries(registry.products ?? {})) {
  if (
    !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id) ||
    !Number.isInteger(wire) ||
    wire < 1 ||
    wire > 65535 ||
    numbers.has(wire)
  ) {
    throw new Error(`Invalid product identity: ${id}`);
  }
  numbers.add(wire);
  const entry = await toml(join(repoRoot, 'products', id, 'product.toml'));
  if (
    typeof entry.model !== 'string' ||
    !/^[A-Z]{2}-[A-Z0-9]+$/.test(entry.model) ||
    models.has(entry.model)
  ) {
    throw new Error(`Invalid or duplicate model: ${id}`);
  }
  models.add(entry.model);
  let image = null;
  if (entry.image) {
    if (typeof entry.image !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*\.png$/.test(entry.image)) {
      throw new Error(`Invalid catalog image: ${id}`);
    }
    const source = join(repoRoot, 'products', id, entry.image);
    const size = await stat(source);
    const metadata = await sharp(source).metadata();
    if (
      !size.isFile() ||
      size.size > 512 * 1024 ||
      metadata.format !== 'png' ||
      !metadata.width ||
      !metadata.height ||
      metadata.width > 1024 ||
      metadata.height > 1024
    ) {
      throw new Error(`Invalid catalog image dimensions or size: ${id}`);
    }
    const target = join(webRoot, 'public/generated/products', `${id}.png`);
    await mkdir(dirname(target), { recursive: true });
    await copyFile(source, target);
    image = {
      src: `/generated/products/${id}.png`,
      width: metadata.width,
      height: metadata.height,
    };
  }
  products.push({ id, wire, model: entry.model, layout: entry.control_layout ?? null, image });
}
if (!products.length) throw new Error('Product registry is empty');
const generated = `// Generated by scripts/build-product-catalog.mjs; do not edit.\nexport const catalog = ${JSON.stringify(products, null, 2)} as const;\n`;
const output = join(webRoot, 'content/products/catalog.generated.ts');
const format = await prettier.resolveConfig(output);
await writeFile(output, await prettier.format(generated, { ...format, filepath: output }));
